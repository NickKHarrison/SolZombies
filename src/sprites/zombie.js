// sprites/zombie.js — zombie / minion / boss pixel sprites (WO7 1.1 / 3.3, Agent A). Pure data,
// Node-safe (no DOM).
//
// Every sprite is an ASCII grid of PALETTE chars ('.' = transparent) parsed once at module load
// with pixel.parseGrid. Same conventions as soldier.js: all sprites face +x (right) at angle 0,
// +y is the zombie's RIGHT side, anchors are sprite-pixel CORNER coordinates, drawn at
// SPRITES.scale (2x). Sizes / anchors (contract, do not change):
//   normal: 16x16 body/legs/tearing/damaged/corpse, anchor (8, 8)   (radius 14 world px)
//   minion: 12x12 body/legs/corpse, anchor (6, 6)
//   boss:   40x40 body/charge/legs/corpse, anchor (20, 20)
//
// Layers (render order): legs (rotate to movement) -> body (rotate to target) -> damaged overlay
// (normal zombies below 50 % HP, same transform as the body).
//
// Normal body (WO7 FIX-4: each tier has its own silhouette AND palette; no olive 'G'/'g'/'L' so the
// soldier's olive uniform is the only green on screen). 1-px 'k' outline, head behind a 'k' ring.
//   walker   slumped: wide hunched back, head drooped low and less forward, ONE arm reaching
//            forward, the other dangling back along the side. Faded blue shirt 'C'/'K', bluish-grey
//            corpse skin 'M'/'m', grey face 'W'/'M', black eye sockets, dark-red mouth.
//   jogger   upright: compact torso, BOTH arms straight forward, torn brown jacket 'o'/'O'/'K' whose
//            tails flap out behind (ragged back edge), sickly yellow-ochre skin/face 'h'/'H', blood 'R'.
//   sprinter lean and forward-leaning: narrow torso, head pushed far forward, both arms swept BACK
//            like running. Near-black 'K'/'m' clothes, white face 'w'/'W', red eyes 'R', and a light
//            'W' rim on the top/back edge inside the outline so it reads on the dark BUNKER floor.
// Damaged overlay: 12 'R'/'r' pixels, each inside (never on the outline of) all 3 bodies and all 3
// tearing frames.
// Legs: 6-frame shamble, bare-toed shoes 'o' + 'S' toes, grey trousers 'm'/'K'. The left foot
// steps (planted foot moves back 3 px/frame = SPRITES.zombieStride 36 / 6 frames / scale 2),
// the right foot is dragged: smaller forward reach, shorter scuffing foot with a trailing 'K'.
//
// Boss tint marker: the crown/helmet region is painted with PALETTE 'p' (#b44dff). 'x' (magenta)
// is reserved for placeholders (isPlaceholder / tests flag it), so boss.tintColor is
// PALETTE.p, NOT '#ff00ff'. 'p' appears nowhere else in the boss sprites, so render can recolour
// exactly the pixels whose RGB equals tintColor (pixel.tint) to levelDef.boss.tint.
// See docs/notes/zombie-sprites.md.
