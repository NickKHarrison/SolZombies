// zombie.js tier names -> normal body variant.
const TIER_VARIANT = { walk: 'walker', jog: 'jogger', sprint: 'sprinter' };

// -> { body, legs, corpse, anchor, tearing } for z.kind ('normal' | 'minion' | 'boss') and
// z.tier. Unknown kinds fall back to 'normal'; unknown tiers to 'walker'. For normal zombies
// corpse / tearing are the tier's own colours; minion and boss have no tearing frame (null).
export function zombieSpriteFor(z) {
  const kind = z && z.kind;
  if (kind === 'boss') {
    const b = ZOMBIE_SPRITES.boss;
    return { body: b.body, legs: b.legs, corpse: b.corpse, anchor: b.anchor, tearing: null };
  }
  if (kind === 'minion') {
    const m = ZOMBIE_SPRITES.minion;
    return { body: m.body, legs: m.legs, corpse: m.corpse, anchor: m.anchor, tearing: null };
  }
  const n = ZOMBIE_SPRITES.normal;
  const variant = TIER_VARIANT[z && z.tier] || 'walker';
  return { body: n.body[variant], legs: n.legs, corpse: n.corpseVariants[variant], anchor: n.anchor, tearing: n.tearingVariants[variant] };
}
